#ifndef __ODOMETER_H
#define __ODOMETER_H

#include "main.h"

/* ============================================================
 * 里程计（采集层：唯一「脉冲 → mm」换算点）
 *
 * 差值法：不丢脉冲（消除原"读-清"空窗造成的左偏）。
 * 车体中心位移 = 左右轮位移的平均值。
 * ============================================================ */

/* ==================== 脉冲 → mm 换算 ====================
 * MM_PER_PULSE = 每轮圈位移 / 每轮圈计数
 *
 * ① 每轮圈位移（齿距口径）—— 已知：
 *      驱动轮 Ø40mm / 14 齿，履带齿距 9mm  →  14 × 9 = 126mm
 *      （等效直径 126/π = 40.1mm，与 Ø40 吻合；比几何 π×40=125.7mm 更准，
 *        因为 126mm 才是履带啮合一周的实际长度）
 *
 * ② 每轮圈计数 —— 已知线数，反推减速比：
 *      编码器 1024 线/圈（电机轴）× 2 倍频 × 减速比 = 61440
 *      ⇒ 反推减速比 = 30:1
 *      ★ 倍频是 2 不是 4：TIM1/TIM8 配的是 TIM_ENCODERMODE_TI1，
 *        只对 TI1 的上下沿计数（见 cubemx/main.c 的 Encoder 模式配置）。
 *      ⚠️ 30:1 是反推值，需对照减速箱铭牌确认。
 *
 * ③ 纯几何系数（无滑移）：126 / 61440 = 0.0020508 mm/脉冲（487.6 脉冲/mm）
 *
 * ④ 当前常量 0.002244 = 纯几何 × 1.094，即比纯几何【大 9.4%】。
 *      这是作者当年实测标定的结果（原记录「509 显示 ≈ 545 实际」＝ ×1.07），
 *      但那次基线是旧节圆 41mm。
 *      ⚠️ 这 9.4% 是「履带滑移 + 有效滚动半径 + 标定噪声」的混合，【尚未实测分离】。
 *         它不是孤立的一个数：Go/Scan/Back 的距离判据、TEST_BASE_SPEED 的
 *         「750 脉冲直道速」都建在它上面，改常量会让所有距离/速度参数集体平移。
 *         改之前必须实测 —— 手动推车走已知 1m，读 enc_total_l 增量：
 *             ≈ 48760 ⇒ 纯几何对；≈ 44560 ⇒ 现标定对。
 *
 * 历史勘误：本行原注释写「π*41/122880 ≈ 0.001048」，其中
 *      122880 是笔误（应为其 1/2 = 61440），且漏记了那次 ×2 ——
 *      照它推导会得到一个小一倍的值，别再用。
 * ============================================================ */
#define MM_PER_PULSE   0.002244f   /* 现用值 = 纯几何 0.0020508 × 1.094，来源见上 */

void  Odom_Sample(void);        /* 每控制周期调一次，读编码器累计距离并换算 */
float Odom_GetDistanceMM(void); /* 累计距离 mm */
float Odom_GetVL(void);         /* 左轮速度 mm/周期 */
float Odom_GetVR(void);         /* 右轮速度 mm/周期 */
void  Odom_Reset(void);         /* 清零（切段/重启时用） */

#endif
